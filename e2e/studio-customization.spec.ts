import {test,expect} from "@playwright/test";
import {mkdirSync} from "node:fs";

test("Studio anatomy editor keeps a live human and camera while changing body and face",async({page})=>{
  test.setTimeout(180_000);
  const errors:string[]=[];
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto("/studio/");
  await expect(page.locator("html")).toHaveAttribute("data-studio-ready","true",{timeout:90_000});
  await page.locator('[data-view="side"]').click();
  await page.getByRole("button",{name:"Body",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Shape the silhouette"})).toBeVisible();
  const age=page.locator('[data-control-id="body:macro/age"] input[type=number]');
  await expect(age).toBeVisible();
  await age.fill("0.03");
  await age.press("Tab");
  await expect(age).toHaveValue("0.03");
  await expect(page.locator("#studio-editor-message")).toBeEmpty({timeout:90_000});
  await expect(page.locator('[data-view="side"]')).toHaveAttribute("aria-pressed","true");
  const viewport=page.locator("#studio-viewport canvas");
  await expect(viewport).toBeVisible();
  await page.locator("#studio-section-reset").click();
  await expect(age).toHaveValue("0.5");
  await page.getByRole("button",{name:"Face",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Shape the face"})).toBeVisible();
  await page.locator("#studio-group").selectOption("Nose");
  const nose=page.locator('[data-control-id="face:noseWidth"] input[type=number]');
  await expect(nose).toBeVisible();
  await nose.fill("0.65");await nose.press("Tab");
  await expect(page.locator("#studio-editor-message")).toBeEmpty({timeout:90_000});
  await page.locator("#studio-advanced").check();
  await page.locator("#studio-control-search").fill("jaw");
  await expect(page.locator(".studio-control").first()).toBeVisible();
  await expect(page.locator("#studio-viewport canvas")).toBeVisible();
  expect(await page.locator("body").evaluate(el=>el.scrollWidth<=innerWidth+1)).toBe(true);
  mkdirSync("test-results/studio",{recursive:true});
  await page.screenshot({path:"test-results/studio/"+test.info().project.name+"-customization.png",fullPage:true});
  expect(errors).toEqual([]);
});
